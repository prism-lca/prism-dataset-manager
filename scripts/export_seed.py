#!/usr/bin/env python3
"""Regenerate supabase/seed.sql from the live Supabase datasets table."""

from __future__ import annotations

import argparse
import json
import os
import re
import urllib.request
from collections import Counter
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "supabase" / "seed.sql"
DATASET_TYPES = (
    "model",
    "process",
    "flow",
    "flow_property",
    "unit_group",
    "source",
    "contact",
)

SCHEMA_SQL = """-- Generated by scripts/export_seed.py from the live Supabase datasets table.
-- Safe to re-run: fixed ids are upserted, and legacy sample ids are removed.
-- Regenerate after intentional live-data changes; do not edit the data rows by hand.

begin;

create table if not exists import_batches (
  id uuid primary key,
  created_by uuid not null default auth.uid() references auth.users(id),
  source_format text not null,
  source_filename text,
  summary jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists datasets (
  id uuid primary key default gen_random_uuid(),
  type text not null check (type in ('model','process','flow','flow_property','unit_group','source','contact')),
  name text not null,
  description text,
  payload jsonb default '{}',
  created_by uuid default auth.uid() references auth.users,
  visibility text not null default 'public' check (visibility in ('public', 'private')),
  import_batch_id uuid references import_batches(id),
  created_at timestamptz default now()
);

alter table datasets add column if not exists visibility text;
alter table datasets add column if not exists import_batch_id uuid references import_batches(id);
alter table datasets alter column created_by set default auth.uid();
alter table datasets alter column visibility set default 'public';
update datasets set visibility = case when created_by is null then 'public' else 'private' end
where visibility is null;
alter table datasets alter column visibility set not null;

alter table datasets enable row level security;
alter table import_batches enable row level security;

revoke all on table import_batches from anon;
grant select, insert on table import_batches to authenticated;

drop policy if exists "public read" on datasets;
drop policy if exists "auth write" on datasets;
drop policy if exists "auth update" on datasets;
drop policy if exists "auth delete" on datasets;
drop policy if exists "read visible datasets" on datasets;
drop policy if exists "create owned datasets" on datasets;
drop policy if exists "update owned datasets" on datasets;
drop policy if exists "delete owned datasets" on datasets;

create policy "read visible datasets" on datasets for select to anon, authenticated
using (visibility = 'public' or created_by = (select auth.uid()));
create policy "create owned datasets" on datasets for insert to authenticated
with check (visibility = 'private' and created_by = (select auth.uid()));
create policy "update owned datasets" on datasets for update to authenticated
using (visibility = 'private' and created_by = (select auth.uid()))
with check (visibility = 'private' and created_by = (select auth.uid()));
create policy "delete owned datasets" on datasets for delete to authenticated
using (visibility = 'private' and created_by = (select auth.uid()));

drop policy if exists "read owned import batches" on import_batches;
drop policy if exists "create owned import batches" on import_batches;
create policy "read owned import batches" on import_batches for select to authenticated
using (created_by = (select auth.uid()));
create policy "create owned import batches" on import_batches for insert to authenticated
with check (created_by = (select auth.uid()));

"""


def load_env(path: Path) -> dict[str, str]:
    values = dict(os.environ)
    if path.exists():
        for raw_line in path.read_text(encoding="utf-8").splitlines():
            line = raw_line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            values.setdefault(key.strip(), value.strip().strip('"').strip("'"))
    return values


def fetch_rows(url: str, anon_key: str) -> list[dict]:
    endpoint = (
        url.rstrip("/")
        + "/rest/v1/datasets"
        + "?select=id,type,name,description,payload,created_at"
        + "&order=type.asc,name.asc,id.asc"
    )
    request = urllib.request.Request(
        endpoint,
        headers={"apikey": anon_key, "Authorization": f"Bearer {anon_key}"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        rows = json.load(response)
    return rows


def validate_rows(rows: list[dict]) -> None:
    required = {"id", "type", "name", "description", "payload", "created_at"}
    for index, row in enumerate(rows, 1):
        missing = required - row.keys()
        if missing:
            raise ValueError(f"row {index} is missing: {', '.join(sorted(missing))}")
        if row["type"] not in DATASET_TYPES:
            raise ValueError(f"row {index} has unsupported type {row['type']!r}")
        if not isinstance(row["payload"], dict):
            raise ValueError(f"row {index} payload is not an object")
    ids = [row["id"] for row in rows]
    if len(ids) != len(set(ids)):
        raise ValueError("the live table contains duplicate ids")


def sql_text(value: str | None) -> str:
    if value is None:
        return "null"
    return "'" + value.replace("'", "''") + "'"


def existing_snapshot_ids(sql: str) -> set[str]:
    return set(
        re.findall(
            r"\('([0-9a-f-]{36})',\s*'(?:model|process|flow|flow_property|unit_group|source|contact)'",
            sql,
        )
    )


def existing_legacy_ids(sql: str) -> set[str]:
    match = re.search(
        r"-- legacy-id-cleanup:start\n(.*?)-- legacy-id-cleanup:end",
        sql,
        flags=re.DOTALL,
    )
    if not match:
        return set()
    return set(re.findall(r"[0-9a-f-]{36}", match.group(1)))


def render(rows: list[dict], legacy_ids: set[str]) -> str:
    live_ids = {row["id"] for row in rows}
    stale_ids = sorted(legacy_ids - live_ids)
    counts = Counter(row["type"] for row in rows)
    count_summary = ", ".join(f"{kind}={counts[kind]}" for kind in DATASET_TYPES if counts[kind])

    parts = [SCHEMA_SQL]
    parts.append(f"-- Snapshot: {len(rows)} rows ({count_summary}).\n")
    parts.append("-- legacy-id-cleanup:start\n")
    if stale_ids:
        values = ",\n  ".join(sql_text(value) for value in stale_ids)
        parts.append("delete from datasets where id in (\n  " + values + "\n);\n")
    else:
        parts.append("-- No legacy ids need removal.\n")
    parts.append("-- legacy-id-cleanup:end\n\n")

    parts.append("insert into datasets (id, type, name, description, payload, created_at) values\n")
    values = []
    for row in rows:
        payload = json.dumps(row["payload"], ensure_ascii=False, separators=(",", ":"))
        values.append(
            "  ("
            + ", ".join(
                [
                    sql_text(row["id"]),
                    sql_text(row["type"]),
                    sql_text(row["name"]),
                    sql_text(row["description"]),
                    sql_text(payload) + "::jsonb",
                    sql_text(row["created_at"]) + "::timestamptz",
                ]
            )
            + ")"
        )
    parts.append(",\n".join(values))
    parts.append(
        "\non conflict (id) do update set\n"
        "  type = excluded.type,\n"
        "  name = excluded.name,\n"
        "  description = excluded.description,\n"
        "  payload = excluded.payload,\n"
        "  created_by = null,\n"
        "  visibility = 'public',\n"
        "  import_batch_id = null,\n"
        "  created_at = excluded.created_at;\n\n"
        "-- Flush deferred graph checks before changing table metadata on a migrated DB.\n"
        "set constraints all immediate;\n"
        "alter table datasets alter column visibility set default 'private';\n\n"
        "alter table datasets drop constraint if exists datasets_private_owner_check;\n"
        "alter table datasets add constraint datasets_private_owner_check\n"
        "check (visibility <> 'private' or created_by is not null);\n\n"
        "commit;\n"
    )
    return "".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--env-file", type=Path, default=ROOT / ".env")
    args = parser.parse_args()

    env = load_env(args.env_file)
    url = env.get("VITE_SUPABASE_URL")
    anon_key = env.get("VITE_SUPABASE_ANON_KEY")
    if not url or not anon_key:
        parser.error("VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY are required")

    rows = fetch_rows(url, anon_key)
    validate_rows(rows)
    old_sql = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
    legacy_ids = existing_snapshot_ids(old_sql) | existing_legacy_ids(old_sql)
    output = render(rows, legacy_ids)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8")
    print(f"Wrote {len(rows)} rows to {args.output}")


if __name__ == "__main__":
    main()
